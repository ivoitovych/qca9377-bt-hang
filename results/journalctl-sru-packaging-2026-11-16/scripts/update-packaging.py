#!/usr/bin/env python3
"""update-packaging.py : house-style headers for the two patches, and the changelog entry in the style of 8.19's.
Only the text before the first 'diff --git' of each patch changes; the code hunks are copied byte for byte."""
import glob
import os

PKG = "$WORKDIR/pkg/packaging"
LP = "NNNNNNN"

info = {
    f"lp{LP}-sd-journal-cache-last-entry-offset-and-journal-file-state.patch": (
        "Wed, 3 Jan 2024 04:27:59 +0900",
        "sd-journal: cache last entry offset and journal file state",
        "99e6f682d3627c2c06d99bb3c3756e448e8d9bd1",
        """When the offset of the last entry object (or last object for journal
files generated by an old journald) is not changed, the timestamps
should be updated by journal_file_read_tail_timestamp() are unchanged.
So, we can drop to call fstat() in the function.

As, the journal header is always mapped, so we can read the offset and
journal file state without calling fstat.
Still, when the last entry offset is changed, we may need to call fstat()
to read the entry object. But, hopefully the number of fstat() call
can be reduced.
""",
    ),
    f"lp{LP}-sd-journal-make-journal_file_read_tail_timestamp-notify-to-the-caller.patch": (
        "Wed, 3 Jan 2024 04:28:03 +0900",
        "sd-journal: make journal_file_read_tail_timestamp() notify to the caller that some new journal entries added",
        "51b2bcf8356b847e7ab778adfad930691713c7ef",
        """Tiny optimization for journal_file_find_newest_for_boot_id().
""",
    ),
}

for name, (date, subject, h, body) in info.items():
    path = f"{PKG}/debian/patches/{name}"
    text = open(path).read()
    diff = text[text.index("diff --git "):]
    header = (
        "From: Yu Watanabe <watanabe.yu+github@gmail.com>\n"
        f"Date: {date}\n"
        f"Subject: {subject}\n"
        f"Origin: upstream, https://github.com/systemd/systemd/commit/{h}\n"
        "Bug: https://github.com/systemd/systemd/issues/31486\n"
        f"Bug-Ubuntu: https://bugs.launchpad.net/ubuntu/+source/systemd/+bug/{LP}\n"
        "\n"
        f"{body}\n"
        f"(cherry picked from commit {h})\n"
        "---\n"
    )
    open(path, "w").write(header + diff)

cl_path = f"{PKG}/debian/changelog"
cl = open(cl_path).read()
old_end = cl.index("systemd (255.4-1ubuntu8.19)")
entry = f"""systemd (255.4-1ubuntu8.20) UNRELEASED; urgency=medium

  * Fix journalctl being very slow on journals with many files (LP: #{LP})
    - d/p/lp{LP}-sd-journal-cache-last-entry-offset-and-journal-file-state.patch,
      d/p/lp{LP}-sd-journal-make-journal_file_read_tail_timestamp-notify-to-the-caller.patch:
      Cherry-pick upstream commits 99e6f682d3 and 51b2bcf835 (v256): stop
      sd-journal from calling fstat() on every open journal file for every
      entry it returns.

 -- <AUTHOR-NAME> <AUTHOR-EMAIL>  Mon, 16 Nov 2026 09:00:00 +0000

"""
open(cl_path, "w").write(entry + cl[old_end:])
print("updated")
