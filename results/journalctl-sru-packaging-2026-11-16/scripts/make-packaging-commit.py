#!/usr/bin/env python3
"""make-packaging-commit.py : add patches 0001 and 0002 to the noble packaging tree as DEP-3 quilt patches,
append them to debian/patches/series, add a changelog entry. Does not commit (the shell script does)."""
import os
import re
import sys

REPO = "$REPO"
PKG = "$WORKDIR/pkg/packaging"
SRC = REPO + "/patches/systemd/journal-file-scaling/"
LP = "NNNNNNN"          # placeholder: no Launchpad bug exists yet; nothing is filed from here

patches = [
    {
        "src": "0001-sd-journal-cache-last-entry-offset-and-journal-file-state.patch",
        "name": f"lp{LP}-sd-journal-cache-last-entry-offset-and-journal-file-state.patch",
        "date": "Wed, 3 Jan 2024 04:27:59 +0900",
        "hash": "99e6f682d3627c2c06d99bb3c3756e448e8d9bd1",
        "subject": "sd-journal: cache last entry offset and journal file state",
        "body": """When the offset of the last entry object (or last object for journal
 files generated by an old journald) is not changed, the timestamps
 should be updated by journal_file_read_tail_timestamp() are unchanged.
 So, we can drop to call fstat() in the function.
 .
 As, the journal header is always mapped, so we can read the offset and
 journal file state without calling fstat.
 Still, when the last entry offset is changed, we may need to call fstat()
 to read the entry object. But, hopefully the number of fstat() call
 can be reduced.""",
    },
    {
        "src": "0002-sd-journal-make-journal_file_read_tail_timestamp-notify-to-t.patch",
        "name": f"lp{LP}-sd-journal-make-journal_file_read_tail_timestamp-notify-to-the-caller.patch",
        "date": "Wed, 3 Jan 2024 04:28:03 +0900",
        "hash": "51b2bcf8356b847e7ab778adfad930691713c7ef",
        "subject": "sd-journal: make journal_file_read_tail_timestamp() notify to the caller that some new journal entries added",
        "body": "Tiny optimization for journal_file_find_newest_for_boot_id().",
    },
]

for p in patches:
    text = open(SRC + p["src"]).read()
    i = text.index("diff --git ")
    diff = text[i:]
    header = (
        "From: Yu Watanabe <watanabe.yu+github@gmail.com>\n"
        f"Date: {p['date']}\n"
        f"Subject: {p['subject']}\n"
        f"Description: {p['subject']}\n"
        f" .\n"
        f" journalctl calls fstat() for every open journal file for every entry it prints, so reading a\n"
        f" journal that is spread over many files costs a system call per file per entry. See\n"
        f" https://github.com/systemd/systemd/issues/31486. This is one of two upstream commits that\n"
        f" remove those calls; it is cherry-picked unchanged from upstream.\n"
        f" .\n"
        f" {p['body']}\n"
        f"Origin: upstream, commit:{p['hash']}\n"
        "Bug: https://github.com/systemd/systemd/issues/31486\n"
        f"Bug-Ubuntu: https://bugs.launchpad.net/bugs/{LP}\n"
        "Applied-Upstream: v256\n"
        "\n"
        f"(cherry picked from commit {p['hash']})\n"
        "---\n"
    )
    with open(f"{PKG}/debian/patches/{p['name']}", "w") as f:
        f.write(header + diff)

with open(f"{PKG}/debian/patches/series", "a") as f:
    for p in patches:
        f.write(p["name"] + "\n")

cl = open(f"{PKG}/debian/changelog").read()
entry = f"""systemd (255.4-1ubuntu8.20) UNRELEASED; urgency=medium

  * Fix journalctl being very slow on journals that span many files
    (LP: #{LP})
    - d/p/lp{LP}-sd-journal-cache-last-entry-offset-and-journal-file-state.patch,
      d/p/lp{LP}-sd-journal-make-journal_file_read_tail_timestamp-notify-to-the-caller.patch:
      Cherry-pick upstream commits 99e6f682d3 and 51b2bcf835 (v256). They
      stop sd-journal from calling fstat() on every open journal file for
      every entry it returns, which made the cost of reading a journal grow
      with the number of files.

 -- <AUTHOR-NAME> <AUTHOR-EMAIL>  Mon, 16 Nov 2026 09:00:00 +0000

"""
open(f"{PKG}/debian/changelog", "w").write(entry + cl)
print("done")
